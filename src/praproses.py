"""praproses.py: rangkaian praproses SIMUTEH (dipakai ulang mulai P5)."""
import json
import cv2
import numpy as np

PARAM_BAWAAN = {
    "lebar": 640,            # sampling: lebar citra kerja (piksel)
    "gamma": 1.0,            # < 1 mencerahkan, > 1 menggelapkan
    "clahe_clip": 2.0,       # 0 berarti CLAHE tidak dipakai
    "clahe_tile": 8,
    "penapis": "median",     # "none", "rerata", "gaussian", "median"
    "kernel": 3,
    "sigma": 1.0,
    "tajam_k": 0.0,          # 0 berarti tanpa penajaman
}

def gamma_lut(g):
    """Fungsi bantu untuk membuat tabel lookup (LUT) koreksi gamma."""
    lut = np.array([255 * (i / 255) ** g for i in range(256)])
    return lut.clip(0, 255).astype(np.uint8)

def praproses(img_bgr, p=None):
    """Urutan: ubah ukuran -> gamma -> CLAHE kanal V -> redam derau -> tajamkan."""
    p = {**PARAM_BAWAAN, **(p or {})}

    # TODO 1: ubah ukuran agar lebar = p["lebar"], rasio aspek tetap[cite: 32]
    tinggi_asli, lebar_asli = img_bgr.shape[:2]
    rasio = p["lebar"] / lebar_asli
    dimensi_baru = (p["lebar"], int(tinggi_asli * rasio))
    img = cv2.resize(img_bgr, dimensi_baru, interpolation=cv2.INTER_AREA)

    # TODO 2: bila p["gamma"] != 1, terapkan koreksi gamma dengan cv2.LUT[cite: 32]
    if p["gamma"] != 1.0:
        img = cv2.LUT(img, gamma_lut(p["gamma"]))

    # TODO 3: bila p["clahe_clip"] > 0, ubah ke HSV, terapkan CLAHE pada kanal V saja, lalu kembalikan ke BGR[cite: 32]
    if p["clahe_clip"] > 0:
        hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
        clahe = cv2.createCLAHE(clipLimit=p["clahe_clip"], tileGridSize=(p["clahe_tile"], p["clahe_tile"]))
        hsv[:, :, 2] = clahe.apply(hsv[:, :, 2])
        img = cv2.cvtColor(hsv, cv2.COLOR_HSV2BGR)

    # TODO 4: redam derau sesuai p["penapis"], p["kernel"], p["sigma"][cite: 32]
    if p["penapis"] != "none":
        k = p["kernel"]
        if p["penapis"] == "rerata":
            img = cv2.blur(img, (k, k))
        elif p["penapis"] == "gaussian":
            img = cv2.GaussianBlur(img, (k, k), p["sigma"])
        elif p["penapis"] == "median":
            img = cv2.medianBlur(img, k)

    # TODO 5: bila p["tajam_k"] > 0, lakukan unsharp masking[cite: 32]
    if p["tajam_k"] > 0:
        blur_img = cv2.GaussianBlur(img, (5, 5), 1.0)
        img = cv2.addWeighted(img, 1 + p["tajam_k"], blur_img, -p["tajam_k"], 0)

    return img

def simpan_param(p, path="../hasil/param_praproses.json"):
    """Menyimpan parameter praproses ke format JSON."""
    with open(path, "w") as f:
        json.dump({**PARAM_BAWAAN, **p}, f, indent=2)